/* LUMEN design contract: source-only checks, no live accounts or service calls. */
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"../..");
const read=path=>readFileSync(resolve(root,path),"utf8");
const html=read("pilot/index.html");
const css=read("pilot/lumen-depth.css");
const image=read("pilot/lumen-orb.svg");
const xjet=read("pilot/icon.svg");
const pwa=JSON.parse(read("pilot/manifest.webmanifest"));
const buildIcons=read("pilot/tools/build-icons.py");
const doc=read("pilot/templates/pilot-document.html");
const mail=read("pilot/templates/pilot-email-confirmation.html");
const company=read("index.html");
assert.match(html,/href="\/pilot\/lumen-depth\.css\?v=/,"LUMEN CSS is linked in Pilot");
assert.equal((html.match(/pilot-lumen-network/g)||[]).length,2,"Guest and account views have the same quiet orbital network");
assert.match(html,/id="goalText"/,"Existing interactive task composer remains intact");
assert.match(html,/id="guestTask"/,"Guest task composer remains intact");
assert.match(html,/id="createGoal"/,"Task start control still exists");
assert.match(html,/id="pilotLanguageSwitcher"/,"Top-right language switch survives redesign");
// Pilot-only brand: the approved X-Jet accompanies, never replaces, the flight orb.
assert.ok(xjet.includes("data:image/webp;base64,"),"Approved X-Jet artwork is embedded in SVG");
const brandB64=xjet.match(/base64,([A-Za-z0-9+/=]+)/)?.[1];
assert.ok(brandB64&&brandB64.length>5000,"X-Jet image data not empty");
const brandBytes=Buffer.from(brandB64,"base64");
assert.equal(brandBytes.subarray(0,4).toString(),"RIFF","X-Jet WebP RIFF");
assert.equal(brandBytes.subarray(8,12).toString(),"WEBP","X-Jet WebP source");
assert.ok(html.includes('rel="icon" type="image/svg+xml" href="/pilot/icon.svg'),"Pilot favicon is linked");
assert.ok(html.includes('rel="apple-touch-icon" sizes="180x180" href="/pilot/apple-touch-icon.png'),"iOS shortcut uses Pilot icon");
assert.ok(css.includes(".pilot-focus .pilot-focus-brand::before"),"Subtle X-Jet wordmark accent");
assert.ok(!css.includes('.pilot-machine-core{background:url("/pilot/icon.svg")'),"Working flight/hero not replaced by logo");
assert.ok(pwa.icons.some(i=>i.src==="/pilot/icon-maskable-512.png"&&i.purpose==="maskable"),"Maskable Android icon");
assert.ok(pwa.icons.some(i=>i.src==="/pilot/icon-192.png"),"192px PWA icon");
assert.ok(pwa.icons.some(i=>i.src==="/pilot/icon-512.png"),"512px PWA icon");
assert.ok(buildIcons.includes("icon-maskable-512.png"),"Deterministic PNG regeneration");
assert.match(css,/\.pilot-focus-composer:focus-within/,"3D task field keeps focus feedback");
assert.match(css,/prefers-reduced-motion/,"Reduced motion support is essential");
assert.match(css,/@media print/,"Printed views remain legible");
assert.match(css,/\.side\s*\{/,"Bottom navigation shares LUMEN appearance");
assert.ok(!/\/pilot\/lumen-depth/.test(company),"Corporate homepage has no Pilot styling");
const embedded=image.match(/data:image\/webp;base64,([A-Za-z0-9+/=]+)/);
assert.ok(embedded,"3D artwork must contain the real cropped reference image");
const encoded=embedded[1];
assert.equal(encoded.length%4,0,"Valid base64 quartet length");
const bytes=Buffer.from(encoded,"base64");
assert.equal(bytes.subarray(0,4).toString(),"RIFF","Valid WebP RIFF marker");
assert.equal(bytes.subarray(8,12).toString(),"WEBP","Valid WebP header");
assert.equal(bytes.readUInt32LE(4)+8,bytes.length,"No truncated WebP asset");
for(const placeholder of ["{{title}}","{{project_name}}","{{date}}","{{verified_status}}","{{body_html_sanitized}}"])assert.ok(doc.includes(placeholder),placeholder);
for(const placeholder of ["{{email_escaped}}","{{confirmation_url_attr_escaped}}"])assert.ok(mail.includes(placeholder),placeholder);
assert.match(html,/function pilotWorkerObstacleRects\(worker\)/,"Avatar checks visible controls");
assert.match(html,/function pilotPositionWorker\(worker,plane\)/,"Avatar has own floor layout");
assert.match(html,/pilotWorkerOverlaps\(figure,rect\)/,"Avatar path avoids controls");
assert.match(html,/worker\.dataset\.groundSafe/,"Safe-ground fallback exists");
assert.match(html,/pilotAttentionRecall\(f\)/,"Avatar returns after human-action cue");
assert.match(css,/@keyframes pilotGroundEnter/,"Avatar enters horizontally on ground");
assert.match(css,/@keyframes pilotGroundLeave/,"Avatar leaves horizontally on ground");
assert.match(css,/pilot-worker-avatar\[hidden\]/,"No-space state must hide the figure");
assert.match(doc,/@media print/,"Deliverables have printable A4 styling");
assert.match(mail,/role="presentation"/,"Email uses compatible table layout");
console.log("PASS LUMEN image integrity, two entry views, 3D field, accessibility, templates, corporate isolation");
